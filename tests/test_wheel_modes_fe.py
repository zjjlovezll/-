"""Pin the shipped finite-element wheelset mode set to the extraction it came from.

The file under ``vehicles/modes`` is generated by ``scripts/wheelset_fe_dump.py`` (Abaqus
python) and ``scripts/wheelset_fe_modes.py`` (system python), which are not run in CI: the
Abaqus job needs a licence and about 20 s.  So the numbers that matter are asserted here
instead — the frequencies the solver will actually use, the nodal diameters measured from the
shapes, and the degenerate pairing the loader insists on.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
import pytest

from velch.wheel_modes import FORMAT, ModeError, ModeSet, load_modes

MODES = Path(__file__).resolve().parents[1] / "vehicles" / "modes" / "CRH3C_wheelset_fe.json"


@pytest.fixture(scope="module")
def modes() -> ModeSet:
    return load_modes(MODES)


def test_the_file_is_the_current_format(modes: ModeSet) -> None:
    payload = json.loads(MODES.read_text(encoding="utf-8"))
    assert payload["format"] == FORMAT
    assert modes.source.startswith("Abaqus 2022")
    assert len(modes.modes) == 33


def test_it_carries_tread_shapes(modes: ModeSet) -> None:
    assert modes.has_shapes
    assert modes.nodes is not None and modes.shapes is not None
    assert modes.nodes.shape == (772, 3)
    assert modes.shapes.shape == (33, 772, 3)
    # every mode must actually move the tread, or a force applied there would be invisible
    per_mode = np.sqrt((modes.shapes ** 2).sum(axis=(1, 2)))
    assert np.all(per_mode > 0.0)


def test_the_rolling_radius_is_the_tread_not_the_flange(modes: ModeSet) -> None:
    # 0.48577 m is the flange tip of this wheel; the rolling circle is 0.460 m, and using the
    # flange radius would mispredict the spin rate by 5.6 % and therefore every split.
    assert modes.radius_m == pytest.approx(0.460, abs=1e-6)


def test_every_travelling_mode_has_a_partner(modes: ModeSet) -> None:
    # this is what the loader enforces, and a real axisymmetric wheel has no split at rest
    speed_m_s = 200.0 / 3.6
    revolutions_per_s = modes.rotational_speed(speed_m_s) / (2.0 * math.pi)
    spins = modes.pair_splits_hz(modes.rotational_speed(speed_m_s))
    assert spins, "the FE set must contain travelling modes"
    for diameter, base, back, forward in spins:
        assert back < base < forward
        # the split is ND revolutions per second each way, so ND * n in Hz, not ND * spin:
        # spin is rad/s and differs by 2 pi, which is exactly the factor the first version missed
        assert (forward - base) == pytest.approx(diameter * revolutions_per_s, abs=1e-6)
        assert (base - back) == pytest.approx(diameter * revolutions_per_s, abs=1e-6)


def test_the_measured_nodal_diameters_match_the_family_sizes(modes: ModeSet) -> None:
    counts: dict[tuple[int, float], int] = {}
    for mode in modes.modes:
        if mode.nodal_diameter > 0:
            counts[(mode.nodal_diameter, round(mode.frequency_hz, 2))] = (
                counts.get((mode.nodal_diameter, round(mode.frequency_hz, 2)), 0) + 1
            )
    # a nodal-diameter-2 family has four modes (two polarisations on each wheel), ND3 four,
    # and every ND1 family two; anything else means the shape measurement disagreed
    assert counts[(2, 347.1)] == 4
    assert counts[(3, 957.32)] == 4
    for (diameter, _frequency), count in counts.items():
        if diameter == 1:
            assert count == 2, f"ND1 family at {_frequency} Hz has {count} modes"


def test_the_lowest_modes_are_what_the_solver_was_run_with(modes: ModeSet) -> None:
    table = [(mode.index, mode.frequency_hz, mode.nodal_diameter, mode.label) for mode in modes.modes]
    assert table[0][0] == 1 and table[0][2] == 0 and table[0][3] == "torsion"
    assert table[0][1] == pytest.approx(76.79, abs=0.01)
    assert table[1][1] == pytest.approx(88.25, abs=0.01)
    by_frequency = {round(mode.frequency_hz, 2): mode.nodal_diameter for mode in modes.modes}
    assert by_frequency[347.1] == 2
    assert by_frequency[957.32] == 3
    assert by_frequency[208.14] == 0


def test_a_truncated_family_is_refused_by_the_loader() -> None:
    payload = json.loads(MODES.read_text(encoding="utf-8"))
    modes = payload["modes"]
    # drop one half of the 2-nodal-diameter family: four modes become three.  Select by
    # frequency alone — the stored value is 347.1 to the print precision but not bit-exactly,
    # so an `index == 9` guard silently matched nothing and the assertion below passed nothing.
    target = next(index for index, item in enumerate(modes) if abs(item["frequency_hz"] - 347.1) < 0.5)
    trimmed = [item for index, item in enumerate(modes) if index != target]
    assert len(trimmed) == len(modes) - 1
    # renumber, so the only remaining defect is the unpaired travelling mode: without this the
    # loader rejects the index gap first and the test would not be testing the pairing rule
    for position, item in enumerate(trimmed):
        item["index"] = position + 1
    payload["modes"] = trimmed
    if payload.get("shapes") is not None:
        # keep the shape array consistent with the modes, or the loader rejects the count
        # before it ever looks at the pairing
        payload["shapes"] = [block for index, block in enumerate(payload["shapes"]) if index != target]
    loaded = ModeSet.from_json(payload)
    # pairing is checked when the rotation matrices are wanted, not at load time: an unpaired
    # travelling mode has no physical meaning, so the refusal belongs at first use
    with pytest.raises(ModeError, match="no degenerate partner"):
        loaded.gyroscopic()


def test_the_split_uses_the_wheel_radius_not_a_guess(modes: ModeSet) -> None:
    for speed_kmh in (200.0, 291.0, 350.0):
        spin = modes.rotational_speed(speed_kmh / 3.6)
        assert spin == pytest.approx(speed_kmh / 3.6 / 0.460, rel=1e-12)
        for diameter, base, back, forward in modes.pair_splits_hz(spin):
            assert forward - back == pytest.approx(2.0 * diameter * spin / (2.0 * math.pi), rel=1e-12)
